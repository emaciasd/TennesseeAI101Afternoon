import { chromium } from 'playwright';
import * as tf from '@tensorflow/tfjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

const fixture=tf.sequential();
fixture.add(tf.layers.globalAveragePooling2d({inputShape:[224,224,3]}));
fixture.add(tf.layers.dense({units:3,activation:'softmax'}));
const weights=[tf.zeros([3,3]),tf.tensor1d([5,-5,-5])];fixture.setWeights(weights);weights.forEach(w=>w.dispose());
let artifacts;
await fixture.save(tf.io.withSaveHandler(async data=>{artifacts=data;return {modelArtifactsInfo:{dateSaved:new Date(),modelTopologyType:'JSON'}};}));
fixture.dispose();
const model={modelTopology:artifacts.modelTopology,weightsManifest:[{paths:['weights.bin'],weights:artifacts.weightSpecs}]};
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream','--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try {
 const context=await browser.newContext({permissions:['camera'],viewport:{width:1440,height:1050},acceptDownloads:true});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/test-model/**',route=>{const path=new URL(route.request().url()).pathname;return route.fulfill(path.endsWith('metadata.json')?{json:{labels:['Correct','Incorrect','Empty'],imageSize:224}}:path.endsWith('model.json')?{json:model}:{body:Buffer.from(artifacts.weightData),contentType:'application/octet-stream'});});
 await page.goto('http://localhost:5173');
 await page.getByRole('heading',{name:'Every part. A clear decision.'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Record inspection'}).isDisabled(),true);
 assert.equal(await page.locator('#model-url').inputValue(),'https://teachablemachine.withgoogle.com/models/fAuwZbUNp/');
 await fs.mkdir('test-results',{recursive:true});await page.screenshot({path:'test-results/desktop.png',fullPage:true});
 await page.locator('#model-url').fill('http://localhost:5173/test-model/');await page.getByRole('button',{name:'Load',exact:true}).click();
 await page.getByText('Model connected · 3 classes').waitFor();
 await page.getByRole('button',{name:'Enable camera'}).click();
 await page.locator('.verdict').filter({hasText:/^GO$/}).waitFor({timeout:30000});
 await page.getByRole('button',{name:'Record inspection'}).click();
 assert.equal(await page.locator('tbody tr').count(),1);
 await page.getByRole('combobox',{name:'NO-GO class',exact:true}).selectOption('Empty');
 await page.getByRole('combobox',{name:'GO class',exact:true}).selectOption('Incorrect');
 await page.getByRole('combobox',{name:'NO-GO class',exact:true}).selectOption('Correct');
 await page.locator('.verdict').filter({hasText:/^NO-GO$/}).waitFor();
 await page.getByRole('button',{name:'Record inspection'}).click();
 await page.locator('#threshold').fill('100');
 await page.locator('.verdict').filter({hasText:/^REVIEW$/}).waitFor();
 await page.getByRole('button',{name:'Record inspection'}).click();
 assert.equal(await page.locator('tbody tr').count(),3);
 await page.getByRole('combobox',{name:'Recording interval'}).selectOption('1');
 await page.getByRole('switch',{name:'Timed recording'}).check();
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('partlens-history-v1')).length>=4);
 await page.getByRole('switch',{name:'Timed recording'}).uncheck();
 const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Export data'}).click();const download=await downloadPromise;
 const content=await fs.readFile(await download.path(),'utf8');assert.match(content,/"GO"/);assert.match(content,/"NO-GO"/);assert.match(content,/"REVIEW"/);
 await page.getByRole('button',{name:'Stop camera'}).click();assert.equal(await page.getByRole('button',{name:'Record inspection'}).isDisabled(),true);
 await page.reload();assert.equal(await page.locator('tbody tr').count()>=4,true);
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:'test-results/mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'mobile must not overflow');
 await page.route('**/missing-model/**',r=>r.fulfill({status:404,body:'Not found'}));await page.locator('#model-url').fill('http://localhost:5173/missing-model/');await page.getByRole('button',{name:'Load',exact:true}).click();await page.getByRole('alert').filter({hasText:'Could not load model'}).waitFor();
 assert.deepEqual(errors,[]);
 console.log('Browser integration passed: model loading, synthetic camera inference, GO/NO-GO/REVIEW, manual/timed recording, CSV export, persisted history, mobile layout, and model failure.');
} finally {await browser.close();}
